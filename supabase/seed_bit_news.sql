Was sind Geflechtschläuche?

Geflechtschläuche sind Schutzschläuche, die aus Kunststoff-Monofilen geflochten werden. Sie werden zum Schutz und zur Bündelung von Kabeln und Litzen verwendet und können durch den großen Anwendungsbereich sehr flexibel eingesetzt werden.

Durch das Zusammenstoßen des Materials vergrößert sich der Durchmesser und die zu schützenden Kabel können eingeführt werden. Sobald der Druck auf den Geflechtschlauch aufgehoben wird, verringert sich der Durchmesser und der Geflechtschlauch legt sich ideal an und bündelt und schützt die Kabel.

​Durch die Verwendung von farbigen Geflechtschläuchen können die Kabelbündel gleichzeitig markiert werden.

Wo werden Geflechtschläuche verwendet?

Geflechtschläuche aus PA 6.6, PET oder PP werden in vielen verschiedenen Branchen, wie z.B. Automotive, Energietechnik oder in der Luft- und Raumfahrt verwendet. Sie dienen der Bündelung von Kabeln und dem mechanischen Schutz von Bauteilen.

Wie werden Geflechtschläuche geschnitten?

Um das Ausfransen der Schlauchenden zu vermeiden, werden Geflechtschläuche thermisch abgelängt. Hierfür empfehlen wir die Verwendung des Heißschneidegeräts HSG-00. Hierbei ist darauf zu achten, dass sich der Geflechtschlauch im aufgedehnten Zustand verkürzt.

Für die Serienproduktion von Kabelbäumen bieten wir die Geflechtschläuche auch fertig geschnitten an. Profitieren Sie hierbei von der Einhaltung geringer Längentoleranzen und hoher Präzision.

