## I

### Von IEC 60684 bis Isolierschlauch

IEC 60684

## Was ist die IEC 60684?

Die IEC 60684 ist eine internationale Norm, die die Anforderungen an flexible elektrische Isolierschläuche regelt. Sie stammt von der International Electrotechnical Commission (IEC) und ist weltweit anerkannt. Die Norm deckt eine Vielzahl von Materialien wie PVC, Polyolefin, PTFE oder Silikon ab und beschreibt deren Eigenschaften, Prüfmethoden und Klassifizierungen.

## Wofür ist die IEC 60684 relevant?

Die IEC 60684 ist besonders relevant für Unternehmen in der Kabelkonfektion, Automotive sowie Elektrotechnik, die Schrumpf- und Isolierschläuche verarbeiten oder weiterverarbeiten. Sie sorgt für eine standardisierte Qualität, Sicherheit und Vergleichbarkeit der eingesetzten Schläuche.

## Wichtige Merkmale nach IEC 60684

- Mechanische Festigkeit (z. B. Zug- und Reißfestigkeit)

- Elektrische Durchschlagsfestigkeit

- Wärmebeständigkeit und Temperaturklassen

- Flammbeständigkeit

- Chemische Beständigkeit

## Gliederung der Norm

Die IEC 60684 ist in mehrere Teile untergliedert, zum Beispiel:

- IEC 60684-1: Allgemeine Anforderungen

- IEC 60684-2: Prüfmethoden

- IEC 60684-3: Spezifische Anforderungen für verschiedene Schlauchtypen

## Warum ist die IEC 60684 wichtig?

Wer nach IEC 60684 zertifizierte Schläuche einsetzt, kann sich auf gleichbleibend hohe Qualität und Sicherheit verlassen. In vielen Projekten ist die Einhaltung dieser Norm eine Voraussetzung für die Zulassung von elektrischen Baugruppen und Kabelsätzen.

## IEC 60684 und Schrumpfschläuche

Viele Schrumpfschläuche aus Polyolefin oder anderen Werkstoffen werden nach der IEC 60684 getestet und klassifiziert. Die Norm hilft dabei, die passenden Produkte für Anwendungen mit hohen Anforderungen an Isolation, Schutz und Temperaturbeständigkeit auszuwählen.

## Fazit

Die IEC 60684 ist eine zentrale Norm für die Auswahl und Qualitätssicherung von Isolier- und Schrumpfschläuchen in technischen Anwendungen. Unternehmen, die hochwertige elektrische Isolation benötigen, sollten auf normgerechte Produkte achten.

