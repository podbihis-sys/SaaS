Als Abriebfestigkeit bezeichnet man die Widerstandsfähigkeit von festen Oberflächen gegenüber mechanischer Beanspruchung, insbesondere gegenüber Reibung. Die Abriebfestigkeit wird von den Oberflächeneigenschaften der beteiligten Stoffe bestimmt.

