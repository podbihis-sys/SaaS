## Häufige Fragen zu Schrumpfschläuchen aus PTFE, FEP & Kynar (FAQ)

### Was ist der Unterschied zwischen PTFE, FEP und Kynar?

PTFE bietet die höchste Temperatur- und Chemikalienbeständigkeit, FEP ist hochtransparent und leicht verformbar, Kynar (PVDF) punktet mit UV-Beständigkeit und mechanischer Festigkeit.

### Welche Anwendungen eignen sich für PTFE-Schrumpfschläuche?

PTFE ist ideal für Hochtemperaturbereiche bis 260 °C, chemisch aggressive Umgebungen und Anwendungen in der Elektronik, Medizintechnik und Luftfahrt.

### Gibt es transparente Varianten?

Ja, die PTFE, FEP und Kynar Schrumpfschläuche sind in transparenter Ausführung erhältlich und eignen sich ideal für Sichtkontrolle in sensiblen Bereichen.

### Kann ich Schrumpfschläuche aus Kynar auch im Außenbereich einsetzen?

Ja, Kynar-Schrumpfschläuche wie BPVDF 175 und 190 sind UV- und witterungsbeständig und daher auch für dauerhafte Outdoor-Anwendungen geeignet.

